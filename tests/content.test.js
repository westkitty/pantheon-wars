// Content contract tests: art registry completeness (A002), authorship and representation rules (A007), locked roster names.
const test = require('node:test'), assert = require('node:assert');
const fs = require('fs'), path = require('path');
const { data } = require('./helpers.js');
const V = require('../tools/validate-data.js');
const ROOT = path.join(__dirname, '..');

test('A002: every emblem, pattern, priest style, atmosphere, icon, VFX, shrine and event art named by the data exists', () => {
  const ids = V.artIds();
  assert.ok(ids.icons.length >= 40 && ids.vfx.length >= 40, 'registries loaded');
  const r = V.validate(data, { artIds: ids });
  assert.deepStrictEqual(r.errors, []);
  const broken = JSON.parse(JSON.stringify(data)); broken.powers[0].icon = 'no_such_icon'; broken.powers[1].vfx = 'no_such_vfx';
  const r2 = V.validate(broken, { artIds: ids });
  assert.ok(r2.errors.some(e => /no_such_icon/.test(e)) && r2.errors.some(e => /no_such_vfx/.test(e)), 'validator catches missing art');
});

test('A007: locked roster names keep their Unicode exactly', () => {
  const names = Object.fromEntries(data.factions.map(f => [f.id, f.name]));
  assert.strictEqual(names.irish, 'The Tuatha Dé Danann');
  assert.strictEqual(names.yoruba, 'The Council of the Òrìṣà');
  assert.strictEqual(names.egyptian, 'The Ennead of the Two Lands');
  assert.strictEqual(data.factions.length, 10);
});

const shipped = () => ['index.html', 'ui/app.js', 'ui/art.js', 'ui/render.js', 'ui/audio.js', 'ui/chronicle.js', 'ui/encyclopedia.js', 'ui/storage.js', 'data/data.js']
  .map(f => [f, fs.readFileSync(path.join(ROOT, f), 'utf8')]);

test('A007: no AI or language-model credits in anything the player sees', () => {
  const bad = /\b(chatgpt|gpt-\d|openai|large language model|LLM|generated by (an )?ai|ai[- ]generated|claude|anthropic)\b/i;
  shipped().forEach(([f, src]) => assert.ok(!bad.test(src), f + ' mentions an AI/LLM credit: ' + (src.match(bad) || [])[0]));
});

test('Content rules: no spider motifs anywhere in shipped content or data', () => {
  const bad = /\b(spider|spiders|arachn\w*|tarantula|cobweb)\b/i;
  shipped().forEach(([f, src]) => assert.ok(!bad.test(src), f + ' contains a spider motif'));
  fs.readdirSync(path.join(ROOT, 'data')).filter(f => f.endsWith('.json')).forEach(f => assert.ok(!bad.test(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8')), 'data/' + f));
});

test('Representation: the Fifth Sun has no sacrifice mechanic or sacrifice wording in its kit', () => {
  const f = data.factions.find(x => x.id === 'mexica');
  const kit = JSON.stringify([f, data.domains.filter(d => d.faction === 'mexica'), data.powers.filter(p => p.faction === 'mexica'), data.shrines.find(s => s.id === f.shrine),
    data.events.filter(e => (e.factions || []).indexOf('mexica') >= 0)]);
  // the representation note may explain the omission; mechanics, names and flavour may not use it
  const noNote = kit.replace(JSON.stringify(f.representation || '').slice(1, -1), '');
  assert.ok(!/sacrific|blood|heart.?offering|xochiyaoyotl/i.test(noNote), 'no sacrifice mechanics or wording');
  const effects = [].concat(...data.powers.filter(p => p.faction === 'mexica').map(p => p.effects)).map(e => e.type);
  assert.ok(effects.indexOf('loseFollowersLargest') < 0, 'no self-harm for gain effects');
});

test('Every faction has four domains, one power per pillar and its own shrine, emblem, pattern and priest family', () => {
  const uniq = k => new Set(data.factions.map(f => f[k])).size;
  ['shrine', 'emblem', 'pattern', 'priestStyle', 'atmosphere'].forEach(k => assert.strictEqual(uniq(k), 10, k));
  data.factions.forEach(f => {
    assert.strictEqual(f.domains.length, 4, f.id);
    const xs = f.powers.map(id => data.powers.find(p => p.id === id).x).sort();
    assert.deepStrictEqual(xs, ['expand', 'exploit', 'explore', 'exterminate'], f.id);
  });
});
